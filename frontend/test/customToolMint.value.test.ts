/* [FEAT-20261016-TOOLMINT] [FEAT-20261016-TAGBIND] The FE half holds no secret, no company, and reads
 * the wire the BE really writes.
 *
 * 1. 🔴 NO CREDENTIAL / NO VENDOR in the new FE files — they ship in the bundle every browser
 *    downloads. The company list, hosts and credentials live on the server only (the brief's rule,
 *    and the reason `test/paymentToolReachable.ui.test.ts` guards the MINT_* block).
 * 2. DRIFT — every wire key `parseToolMintCatalog` reads, and both route paths, exist in the BE
 *    source (omnidesk-api-loanv1 while the lane is open, omnidesk-api after merge). Missing BE ⇒ SKIPPED
 *    with the reason, never a silent pass (same pattern as `noticeCardGate.value.test.ts`).
 * 3. The parser: the BE-generated fixture → 3 companies; null / malformed → null (no buttons).
 */
import { describe, it, expect } from 'vitest';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

import CATALOG from './fixtures/toolMintCatalog.loan.json';
import { parseToolMintCatalog } from '../services/hook/toolMint';

const ROOT = join(__dirname, '..');
const NEW_FILES = [
  'services/hook/toolMint.ts',
  ...readdirSync(join(ROOT, 'components/hook/custom-tools')).map((f) => `components/hook/custom-tools/${f}`),
];
const read = (p: string) => readFileSync(join(ROOT, p), 'utf8');
/* comments name the very things forbidden ("NO CREDENTIAL", file paths) — judge the code only.
   ⚠️ a `//` right after `:` is a URL (`https://…`), not a comment — stripping it would hide the
   very host this guard looks for (mutation FM10 survived the first version for exactly that). */
const code = (p: string) => read(p).replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');

describe('[TOOLMINT] 🔴 the new FE files carry no secret and no company', () => {
  it('the folder has the pieces we expect (a guard over an empty list proves nothing)', () => {
    expect(NEW_FILES).toEqual(expect.arrayContaining([
      'services/hook/toolMint.ts',
      'components/hook/custom-tools/ToolMintBar.tsx',
      'components/hook/custom-tools/BindTagsButton.tsx',
      'components/hook/custom-tools/toolMintPreset.ts',
    ]));
  });

  it.each(NEW_FILES)('%s — no 32-hex literal, no non-empty password/secret/token/api_key literal', (f) => {
    const s = code(f);
    expect(s).not.toMatch(/[0-9a-fA-F]{32,}/);
    expect(s).not.toMatch(/(password|secret|token|api_key)\s*:\s*['"`][^'"`]+['"`]/i);
  });

  it.each(NEW_FILES)('%s — no partner host or company name (the server declares them)', (f) => {
    const s = code(f);
    expect(s).not.toMatch(/acme|globex|example|https?:\/\//i);
  });
});

const BE_CANDIDATES = ['../backend'].map((p) => join(ROOT, p));
const BE = BE_CANDIDATES.find((p) => existsSync(join(p, 'src/modules/customer-provider/features/tool-mint.ts')));

describe.skipIf(!BE)(`[TOOLMINT] drift — the FE reads what the BE writes (BE: ${BE ?? 'NOT FOUND — skipped'})`, () => {
  const be = (p: string) => readFileSync(join(BE!, p), 'utf8');

  it('every wire key the parser reads is written by `toolMintWire`', () => {
    const wire = be('src/modules/customer-provider/features/tool-mint.ts');
    for (const k of ['id', 'label', 'tool_name', 'ready', 'missing', 'invalid', 'base_url', 'companies', 'template', 'auth_type', 'timeout_ms', 'endpoints']) {
      expect(wire, `BE toolMintWire must still write "${k}"`).toMatch(new RegExp(`\\b${k}\\b`));
    }
    expect(be('src/modules/hooks/tool-mint/tool-mint.controller.ts')).toContain('tool_mint');
  });

  it('both routes the FE calls are the BE controllers\' paths', () => {
    expect(be('src/modules/hooks/tool-mint/tool-mint.controller.ts')).toContain("@Controller('api/custom-tool-mint')");
    expect(be('src/modules/hooks/tool-tag-bind/tool-tag-bind.controller.ts')).toContain("@Controller('api/custom-tool-tag-bind')");
    const svc = read('services/hook/toolMint.ts');
    expect(svc).toContain('/api/custom-tool-mint');
    expect(svc).toContain('/api/custom-tool-tag-bind/');
  });

  it('the fixture was generated by the BE script, not typed (its company ids are the BE rows)', () => {
    const rows = be('src/modules/customer-provider/providers/loan-v1/tool-mint.ts');
    for (const c of (CATALOG as any).data.tool_mint.companies) {
      expect(rows).toContain(`id: '${c.id}'`);
      expect(rows).toContain(`toolName: '${c.tool_name}'`);
    }
    expect(JSON.stringify(CATALOG)).not.toMatch(/SENTINEL/);
  });
});

describe('[TOOLMINT] parseToolMintCatalog', () => {
  it('⭐ the BE answer → 3 companies, readiness and missing KEY names kept', () => {
    const c = parseToolMintCatalog((CATALOG as any).data);
    expect(c?.companies.map((x) => [x.id, x.toolName, x.ready])).toEqual([
      ['demo', 'loan_demo', true],
      ['acme', 'loan_acme', false],
      ['examplepartner', 'loan_examplepartner', false],
    ]);
    expect(c?.companies[1]?.missing).toEqual(['LOAN_TOOL_ACME_USERNAME', 'LOAN_TOOL_ACME_PASSWORD']);
    expect(c?.template.endpoints).toHaveLength(6);
    expect(c?.template.authType).toBe('jwt_login');
  });
  it('⭐ PIN — shop-api (`tool_mint: null`), no data, garbage ⇒ null', () => {
    expect(parseToolMintCatalog({ tool_mint: null })).toBeNull();
    expect(parseToolMintCatalog(undefined)).toBeNull();
    expect(parseToolMintCatalog([])).toBeNull();
    expect(parseToolMintCatalog({ tool_mint: { companies: 'x', template: {} } })).toBeNull();
    expect(parseToolMintCatalog({ tool_mint: { companies: [], template: {} } })).toBeNull();
  });
});
