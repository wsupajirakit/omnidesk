/**
 * [FIX-20260825-TAGSELECTALL] "customer tag เลือกทั้งหมดไม่ได้"
 *
 * เจ้าของแจ้ง 25/08 · ต้นเหตุอยู่ที่ `TagValuePicker`:
 *   เดิม `valueForOp(op, op === 'in' ? next : next.slice(-1))`
 *   ⇒ ตอน op เป็น `eq` (ค่าเริ่มต้น) การเลือกหลายค่า — รวมปุ่ม "เลือกทั้งหมด" —
 *     ถูก **ตัดเหลือตัวสุดท้ายเงียบ ๆ** ผู้ใช้เห็นเป็นปุ่มเสีย
 *
 * `customer_tag` รองรับ ops `['eq','in']` ฝั่ง BE อยู่แล้ว
 * (`audience-source.registry.ts:250`) ⇒ เลือกหลายค่า = ขอสลับเป็น `in`
 * ไม่ใช่ทิ้งค่า
 *
 * ── [FIX-20260828-RULEONEUPDATE] ไฟล์นี้เคยมีสำเนาลอจิกอยู่ในตัวเอง ─────────
 * 🔴 เดิมไฟล์นี้ประกาศ `onChangeLogic()` ที่ **คัดลอก** ตัว `onChange` ของ
 *    `TagValuePicker` มาไว้เอง แล้วเทสสำเนานั้น — พร้อมคอมเมนต์ว่า "จำลองตรรกะ
 *    ตามที่เขียนจริง" ซึ่งเป็นคำสัญญาที่ไม่มีอะไรบังคับให้เป็นจริง
 *    วันที่คอมโพเนนต์เปลี่ยนจากเรียกสองครั้ง (`onOpChange` แล้ว `onChange`) มาเป็น
 *    **เรียกครั้งเดียวพก op มาด้วย** สำเนานี้ยังเขียวทั้งดุ้น ทั้งที่มันวัดโค้ดที่
 *    ไม่มีอยู่แล้ว — กับดักเดียวกับที่ทำให้บั๊กจริงหลุดไปถึง stg
 * ⇒ สำเนาถูกลบทิ้ง · ไฟล์นี้เหลือหน้าที่เดียวคือปัก **`valueForOp` ตัวจริง**
 *   ส่วนกติกา "เลือกหลายค่า ⇒ สลับเป็น in ในการเรียกครั้งเดียว" ย้ายไปปักกับ
 *   **คอมโพเนนต์จริง** ที่ `broadcastTierTagUnlock.dom.test.tsx` และ
 *   `broadcastTagPicker.dom.test.tsx` ซึ่ง render ของจริงและจับ `onChange` จริง
 *   ⚠️ ห้ามเอาสำเนากลับมา — เทสที่ก๊อปลอจิกจะเขียวต่อไปหลังโค้ดเปลี่ยนเสมอ
 */
import { describe, it, expect } from 'vitest';
import { valueForOp } from '../components/campaign/audience/tagOptions';

describe('[TAGSELECTALL] valueForOp — รูปค่าที่แต่ละ operator ต้องได้', () => {
  it('⭐⭐ in ⇒ เก็บครบทุกค่า ไม่ตัดทิ้ง', () => {
    expect(valueForOp('in', ['t1', 't2', 't3'])).toEqual(['t1', 't2', 't3']);
  });

  it('⭐ eq ⇒ ค่าเดียว (ตัวแรก) — นี่คือเหตุผลที่หลายค่าต้องสลับเป็น in', () => {
    /* `eq` เก็บได้ค่าเดียวจริง ๆ ⇒ ถ้าคอมโพเนนต์ส่งหลายค่ามาโดยไม่สลับ op
       ค่าจะหายไปเงียบ ๆ · BE ก็ปฏิเสธทั้งใบ (customer-tag.resolver:
       `"eq" holds one tag, but this condition names N`) */
    expect(valueForOp('eq', ['t9', 't8'])).toBe('t9');
  });

  it('eq ที่ไม่มีใครเลือก ⇒ สตริงว่าง ไม่ใช่ undefined', () => {
    /* 🔴 `''` ไม่ใช่ `undefined` และไม่ใช่ `[]` — ช่อง text เดิมส่ง `''` เมื่อไม่เลือก
       อะไร ตัวสร้าง filter ฝั่ง BE จึงอ่านค่านี้ได้อยู่แล้ว เปลี่ยนเมื่อไหร่ = เปลี่ยน
       ความหมายของกฎที่เซฟไว้แล้ว */
    expect(valueForOp('eq', [])).toBe('');
  });

  it('in ที่ไม่มีใครเลือก ⇒ อาร์เรย์ว่าง', () => {
    expect(valueForOp('in', [])).toEqual([]);
  });

  it('in คืนอาร์เรย์ใบใหม่ ไม่ใช่ตัวเดิมที่ส่งเข้ามา', () => {
    /* กันการแก้ค่าที่ถืออยู่ในสเตตของตัวเลือกโดยไม่ตั้งใจ */
    const src = ['a', 'b'];
    const out = valueForOp('in', src) as string[];
    expect(out).toEqual(src);
    expect(out).not.toBe(src);
  });
});
