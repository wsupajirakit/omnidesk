describe('[TOOLMINT] the server\'s refusal reaches the admin (live 16/10: the BE answers `{ error }`)', () => {
  beforeEach(() => { state.mode = 'loan'; });

  it('⭐ mint refused 409 ⇒ the BE\'s own sentence is shown, not a bare HTTP code', async () => {
    state.mintReply = { status: 409, body: { error: 'มี tool "loan_demo" อยู่แล้ว — ไม่เขียนทับ (แก้ที่ tool เดิมได้เลย)' } };
    const { container } = await renderPage();
    fireEvent.click(byText(container, /Mint demo/)!);
    await waitFor(() => { if (!container.textContent?.includes('ไม่เขียนทับ')) throw new Error('reason not shown'); });
  });

  it('⭐ env incomplete 400 (pre-shaped envelope) ⇒ the sentence is shown', async () => {
    state.mintReply = { status: 400, body: { success: false, error: 'env ของ demo ยังไม่ครบ — mint ได้แค่โครง', missing: ['LOAN_TOOL_DEMO_PASSWORD'] } };
    const { container } = await renderPage();
    fireEvent.click(byText(container, /Mint demo/)!);
    await waitFor(() => { if (!container.textContent?.includes('mint ได้แค่โครง')) throw new Error('reason not shown'); });
  });

  it('⭐ bind refused ⇒ the BE\'s sentence is in the alert', async () => {
    state.bindReply = { status: 404, body: { error: 'ไม่พบ custom tool' } };
    const { container } = await renderPage();
    fireEvent.click(container.querySelector('[data-testid="bind-tags-btn"]') as HTMLButtonElement);
    await waitFor(() => { if (!document.body.textContent?.includes('ไม่พบ custom tool')) throw new Error('reason not shown'); });
  });
});
