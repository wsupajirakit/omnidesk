describe('[TOOLMINT] TARGET — loan: one button per company, drawn from the BE answer', () => {
  beforeEach(() => { state.mode = 'loan'; });

  it('⭐ demo (env complete) ⇒ "Mint demo" · Acme / Globex (incomplete) ⇒ "เติมโครง" + the missing KEY names', async () => {
    const { container } = await renderPage();
    const bar = container.querySelector('[data-testid="tool-mint-bar"]');
    expect(bar).not.toBeNull();
    expect(byText(container, /Mint demo/)).toBeTruthy();
    expect(byText(container, /เติมโครง Acme/)).toBeTruthy();
    expect(byText(container, /เติมโครง Globex/)).toBeTruthy();
    expect(bar!.textContent).toContain('LOAN_TOOL_ACME_USERNAME');
    expect(bar!.textContent).toContain('LOAN_TOOL_GLOBEX_BASE_URL');
  });

  it('🔴 no username / password value ever reaches the page', async () => {
    const { container } = await renderPage();
    expect(container.innerHTML).not.toMatch(/SENTINEL/);
  });

  it('⭐ press "Mint demo" ⇒ POST /api/custom-tool-mint/demo, then the list reloads', async () => {
    const { container } = await renderPage();
    const before = listCustomTools.mock.calls.length;
    fireEvent.click(byText(container, /Mint demo/)!);
    await waitFor(() => {
      if (!state.calls.some((c) => c.method === 'POST' && c.url.endsWith('/api/custom-tool-mint/demo'))) throw new Error('no mint POST');
    });
    await waitFor(() => { if (listCustomTools.mock.calls.length <= before) throw new Error('list not reloaded'); });
    await waitFor(() => { if (!container.textContent?.includes('loan_demo')) throw new Error('no result shown'); });
  });

  it('a company whose tool name is already in the list ⇒ its mint button is disabled', async () => {
    state.tools = [TOOL, { ...TOOL, id: 'tool-2', _id: 'tool-2', name: 'loan_demo' }];
    const { container } = await renderPage();
    const b = buttons(container).find((x) => x.getAttribute('data-company') === 'demo');
    expect(b).toBeTruthy();
    expect(b!.disabled).toBe(true);
  });

  it('⭐ ROUND TRIP — "เติมโครง Acme" ⇒ form filled ⇒ save ⇒ the request body carries every template endpoint field', async () => {
    const { container } = await renderPage();
    fireEvent.click(byText(container, /เติมโครง Acme/)!);
    await waitFor(() => {
      const inputs = Array.from(container.querySelectorAll('input')) as HTMLInputElement[];
      if (!inputs.some((i) => i.value === 'loan_acme')) throw new Error('form not filled');
    });
    const inputs = Array.from(container.querySelectorAll('input')) as HTMLInputElement[];
    expect(inputs.some((i) => i.value === 'https://acme.example.test')).toBe(true);
    fireEvent.click(byText(container, /^บันทึก$/)!);
    await waitFor(() => { if (createCustomTool.mock.calls.length === 0) throw new Error('not saved'); });
    const body = createCustomTool.mock.calls[0]![0] as any;
    expect(body.name).toBe('loan_acme');
    expect(body.base_url).toBe('https://acme.example.test');
    expect(body.auth_type).toBe('jwt_login');
    expect(body.timeout_ms).toBe(4000);
    expect(body.endpoints.map((e: any) => e.key)).toEqual(TEMPLATE_ENDPOINTS.map((e) => e.key));
    for (const want of TEMPLATE_ENDPOINTS) {
      const got = body.endpoints.find((e: any) => e.key === want.key);
      for (const f of ['method', 'path', 'purpose', 'require_jwt', 'request_type', 'payload', 'result_rules', 'is_profile', 'is_login']) {
        if (want[f] === undefined) continue;
        expect({ key: want.key, f, v: got[f] }).toEqual({ key: want.key, f, v: want[f] });
      }
      if (want.profile_map) expect(got.profile_map).toMatchObject({ name: want.profile_map.name, phone: want.profile_map.phone, code: want.profile_map.code });
    }
    /* the admin typed no credentials — the skeleton carries none */
    expect(body.password).toBe('');
    expect(body.username).toBe('');
  });
});

