/**
 * [UI-20260828-DISCARDGUARD] "ยกเลิก" ต้องถามก่อน ถ้ามีงานที่จะหาย
 * ===========================================================================
 * ปุ่มยกเลิกของฟอร์มบรอดแคสต์ปิดหน้าต่างทิ้งทันทีที่กด · ฟอร์มนี้ยาว 6 ขั้น
 * ⇒ พลาดไปโดนครั้งเดียวคืองานทั้งใบหายโดยไม่มีอะไรถามสักคำ
 *
 * 🔴 ถามเฉพาะตอนมีอะไรจะเสียจริง ๆ. กล่องยืนยันที่เด้งทุกครั้งแม้ยังไม่ได้แก้อะไร
 *    จะถูกกดผ่านจนติดเป็นนิสัย แล้ววันที่มันเด้งเพราะมีงานค้างจริงก็จะโดนกดผ่าน
 *    ไปด้วย — ตัวกันที่ร้องทุกครั้งเท่ากับไม่มีตัวกัน
 *
 * ⚠️ เทียบด้วย `JSON.stringify` โดยตั้งใจ ไม่ใช่ deep-equal ราย field:
 *    ตัวที่เทียบคือ state ของฟอร์มซึ่งเป็นข้อมูลล้วน (สตริง/ตัวเลข/อาร์เรย์/ออบเจกต์
 *    ธรรมดา) ไม่มีฟังก์ชัน ไม่มี Date ไม่มีค่าที่วนอ้างตัวเอง · การเทียบทีละ field
 *    ต้องมีคนคอยไล่เพิ่มทุกครั้งที่ฟอร์มมี field ใหม่ ซึ่งเป็นหนี้ที่ลืมง่ายที่สุด
 *    และเงียบที่สุด (ลืมแล้วตัวกันจะไม่ร้องทั้งที่งานหาย)
 *    ⚠️ ผลข้างเคียงที่รับไว้: ลำดับคีย์ที่ต่างกันจะนับว่า "แก้แล้ว" ทั้งที่ค่าเท่าเดิม
 *       ยอมได้ เพราะพลาดไปทาง "ถามเกิน" เสียแค่คลิกเดียว แต่พลาดไปทาง
 *       "ไม่ถาม" เสียงานทั้งใบ
 *
 * ⚠️ ต้องเรียก `mark()` ทุกครั้งที่ฟอร์มถูก **โหลดค่าเริ่มต้น** ใหม่ (เปิดใบเดิมมาแก้
 *    หรือรีเซ็ตเป็นใบเปล่า) ไม่ใช่แค่ตอน mount — ไม่งั้นค่าที่โหลดมาเองจะถูกนับ
 *    เป็น "ผู้ใช้แก้" ตั้งแต่วินาทีแรก
 *
 * revert: ลบไฟล์นี้ + `useUnsavedEdits` ที่ `BroadcastFormModal` แล้วปุ่มยกเลิก
 *   จะกลับไปปิดทันทีโดยไม่ถาม
 */
import { useRef } from 'react';

/**
 * ฟอร์มถูกแก้ไปจากค่าที่โหลดมาแล้วหรือยัง
 *
 * @param value   state ปัจจุบันของฟอร์ม
 * @param resetKey ค่าที่ **เปลี่ยนทุกครั้งที่ฟอร์มถูกโหลดค่าตั้งต้นใหม่** — ตัวนี้คือ
 *   สัญญาณ "เริ่มนับใหม่" · ต้องเปลี่ยนใน render รอบเดียวกับที่ `value` ถูกตั้งค่า
 *   ตั้งต้น (React รวม state update ที่เกิดใน effect เดียวกันเป็นชุดเดียว)
 *   ⚠️ ห้ามใช้ `isOpen` เป็น resetKey — ตอน `isOpen` เพิ่งเป็น true ค่าฟอร์มยังเป็น
 *      ของใบก่อนอยู่ effect ที่โหลดค่าจริงยังไม่ทำงาน ⇒ จะจำค่าผิดใบเป็นค่าตั้งต้น
 *      แล้วตอบว่า "แก้แล้ว" ตั้งแต่วินาทีแรก
 */
export function useUnsavedEdits<T>(value: T, resetKey: unknown): boolean {
  const baseline = useRef<string | null>(null);
  /* ค่าเริ่มต้นเป็น object ใบเฉพาะ เพื่อให้ render แรกนับว่า "resetKey เปลี่ยน"
     เสมอ ไม่ว่าผู้เรียกจะส่ง 0 / null / undefined มาก็ตาม */
  const seenKey = useRef<unknown>({});

  /* ซิงก์ระหว่าง render ไม่ใช่ใน effect — ต้องได้คำตอบทันในรอบที่ค่าตั้งต้นมาถึง
     ถ้ารอ effect จะมีอยู่หนึ่ง render ที่ตอบว่า "แก้แล้ว" ทั้งที่ยังไม่มีใครแตะ
     (การเขียน ref ระหว่าง render ไม่ทำให้เกิด render ซ้ำ และไม่ใช่ side effect
     ที่มองเห็นจากข้างนอก) */
  if (seenKey.current !== resetKey) {
    seenKey.current = resetKey;
    baseline.current = JSON.stringify(value);
    return false;
  }

  if (baseline.current === null) return false;
  return JSON.stringify(value) !== baseline.current;
}
