/** เติม 0 ข้างหน้าให้ครบ 2 หลัก */
const pad2 = (n: number): string => String(n).padStart(2, '0');

/**
 * วันที่ปัจจุบันรูปแบบ `ddmmyy` — ปี **ค.ศ.** สองหลัก
 *
 * ใช้เวลาเครื่องของผู้ใช้ (แอดมินอยู่ไทยทั้งหมด) จึงไม่บังคับ timeZone —
 * การบังคับ `Asia/Bangkok` จะทำให้ค่าที่ได้ต่างจากนาฬิกาบนจอของคนกรอกเอง
 *
 * @param now ฉีดเวลาได้เพื่อให้เทสไม่ผูกกับวันจริง
 */
export const todayDdMmYy = (now: Date = new Date()): string =>
  `${pad2(now.getDate())}${pad2(now.getMonth() + 1)}${String(now.getFullYear()).slice(-2)}`;

/**
 * คืนค่า `description` ที่ควรใช้ — เติมวันที่ให้ก็ต่อเมื่อ **ว่างจริง**
 *
 * ครอบคลุมทุกชนิดที่ API เคยส่งมาจริง: `undefined` (ไม่มี key),
 * `null` (HookFormModal.tsx:772 โหลดมาตรง ๆ ไม่มี `|| ''`), `''`, และสตริงที่มี
 * แต่ช่องว่าง (validation ตรวจ `.trim()` ⇒ เว้นวรรคล้วนก็ถือว่าว่าง)
 *
 * ค่าที่มีอยู่แล้ว **คืนกลับไปเหมือนเดิมทุกตัวอักษร** — ไม่ trim ไม่แต่ง เพราะ
 * คำอธิบายที่แอดมินเขียนไว้เป็นของเขา ไม่ใช่ของเรา
 */
export const resolveHookDescription = (
  current: unknown,
  now: Date = new Date(),
): string => {
  if (typeof current === 'string' && current.trim()) return current;
  return todayDdMmYy(now);
};
