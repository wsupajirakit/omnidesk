/**
 * [FEAT-20260824-CLAIMPROFILE] "เคสนี้เพิ่งกลายเป็นของแอดมินคนนี้" — กฎเดียวกลาง
 *
 * WHAT: ตอบคำถามเดียว — เคสที่เปิดอยู่ "เพิ่งถูกรับ" หรือเปล่า
 *       (นิยาม: ticket **ใบเดิม** เปลี่ยนจากไม่ใช่ของเรา → เป็นของเรา)
 *
 * WHY: เจ้าของสั่งว่าปุ่ม "กดรับเคสเพื่อสนทนา" · "รับเคสต่อ" (แย่งจากแอดมินอื่น) ·
 *      "เปิดเคส" (เปิดเคสที่ปิดแล้ว) ทั้งสามปุ่ม ต้อง fetch raw profile ใหม่ทันที
 *      และ panel ขวาต้องเป็นข้อมูลสดตอนนั้น
 *      ถ้าไปแปะที่ handler ทีละปุ่ม = โค้ดซ้ำ 3 ที่ และปุ่มที่ 4 ในอนาคตจะลืมแน่นอน
 *      จึงจับที่ "รอยต่อ" เดียวที่ทั้งสามปุ่มต้องผ่าน: เจ้าของเคสเปลี่ยนมาเป็นเรา
 *
 * ⚠️ WHY การเทียบ ticketId ถึงสำคัญ (จุดที่ไม่ชัดในตัวมันเอง):
 *      ถ้าดูแค่ isMine false→true เฉย ๆ การ "สลับห้อง" จากเคสของแอดมินอื่น
 *      ไปเคสที่เป็นของเราอยู่แล้ว จะเห็นเป็น false→true ด้วย → ยิงดึงโปรไฟล์
 *      ทุกครั้งที่สลับห้อง ทั้งที่ไม่มีใครกดรับอะไรเลย (bug จริง + ยิง API มั่ว)
 *      กฎจึงบังคับว่าต้องเป็น **ลูกค้าคนเดียวกัน** เท่านั้น
 *
 * ⚠️⚠️ WHY คีย์เป็น "ลูกค้า" ไม่ใช่ ticket._id (เกือบพลาด — จับได้ตอนเขียนเทส):
 *      ปุ่ม "เปิดเคส" (reopen) ได้ ticket **ใบใหม่** กลับมา — `reopenTicketCard.ts:35`
 *      เอา `fresh._id` มาทับ ⇒ ถ้าคีย์ด้วย ticket._id จะเห็นเป็น "คนละใบ" แล้ว
 *      ไม่ยิง ⇒ ปุ่มที่เจ้าของสั่งมาชัด ๆ จะ **ตายเงียบ** ทั้งที่เทสเขียว
 *      ทั้งสามปุ่มเป็นลูกค้าคนเดิมเสมอ · สลับห้อง = คนละลูกค้า ⇒ ยังกันได้เหมือนเดิม
 *
 * Pure on purpose (แนวเดียวกับ pages/chat/reopenTicketCard.ts ข้าง ๆ) — กฎนี้
 * ตรึงด้วย test/caseTakenProfileRefresh.value.test.ts ได้โดยไม่ต้อง mount หน้า
 * TicketChat ที่ยาวสี่พันบรรทัด
 *
 * revert: ลบไฟล์นี้ + useEffect marker เดียวกันใน pages/chat/TicketChat.tsx
 */

export interface CaseOwnership {
  /**
   * ตัวตนของ "ลูกค้า" ที่เปิดอยู่ — ใช้ `line_user_id` ไม่ใช่ ticket._id
   * (reopen เปลี่ยน _id ทุกครั้ง — ดูกับดักในหัวไฟล์) · null = ไม่ได้เปิดเคสไหนเลย
   */
  ticketId: string | null;
  /** เคสนี้อยู่ในมือแอดมินคนที่ล็อกอินอยู่หรือไม่ (job_status===1 && admin คือเรา) */
  isMine: boolean;
}

/**
 * ยิงดึงโปรไฟล์ใหม่หรือไม่ — true เฉพาะตอน **ลูกค้าคนเดิม** พลิกจาก
 * ไม่ใช่ของเรา → เป็นของเรา
 *
 * ไม่ยิงเมื่อ: สลับไปห้องอื่น (คนละลูกค้า) · เป็นของเราอยู่แล้ว · เพิ่งเสียเคสไป ·
 * ไม่มีเคสเปิดอยู่ทั้งสองฝั่ง
 */
export const shouldFireCaseTaken = (prev: CaseOwnership, next: CaseOwnership): boolean => {
  if (!next.ticketId) return false;                 // ไม่มีเคสเปิดอยู่ = ไม่มีอะไรให้ดึง
  if (prev.ticketId !== next.ticketId) return false; // คนละคน = "สลับห้อง" ไม่ใช่ "เพิ่งรับ"
  return !prev.isMine && next.isMine;                // พลิกจริงเท่านั้น
};
