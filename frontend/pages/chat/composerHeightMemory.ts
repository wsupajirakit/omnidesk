/* [FEAT-20260830-INPUT30] 120 → 156 (+30%) — owner 30/08: the default-mode
   input box, with no tray open, is 30% taller. Touches ONLY the default: a
   remembered dragged height still wins, locked rooms still get IDLE. */
export const DEFAULT_COMPOSER_H = 156;

/**
 * ความสูงของ **ห้องที่พิมพ์ไม่ได้** — บอทดูแล · รอรับเคส · เคสปิด · เคสคนอื่น
 *
 * เจ้าของแจ้งรอบสอง 25/08 พร้อมภาพ: *"ทำไมกล่องพวกที่ไม่ได้พร้อมแชท มันยังสูงอยู่"*
 * ⇒ รอบแรกผมแก้ให้ "กลับไปค่าเริ่มต้น" ซึ่งคือ 120 = ความสูงของกล่องพิมพ์ปกติ
 *   แต่ห้องพวกนี้ **พิมพ์ไม่ได้อยู่แล้ว** (overlay ทับ) จึงไม่ต้องกินที่ขนาดนั้น
 *   เจ้าของเคาะ: "เอาแค่ 60"
 *
 * ⚠️ 25/08 รอบสอง: เจ้าของสั่งลดอีกเหลือ **40** — *"กล่อง box บอทดูแล และกล่องอื่นๆ
 *    ที่ไม่ใช่การคุย ลด เหลือ 40"* (เดิม 60 · ก่อนหน้านั้นคือ DEFAULT 120)
 *    40 อยู่เหนือ `MIN_H` (39) แค่ 1px คือเตี้ยที่สุดเท่าที่ตัวลากยอมให้เป็น
 *    ⇒ ถ้าจะลดอีกต้องลด `MIN_H` ด้วย ซึ่งจะกระทบการลากในห้องที่คุยจริง
 */
/* [UI-20260826-IDLE20] 28 → 20 (−30%, รอบที่ห้า)
   ประวัติของเลขนี้: 120 → 60 → 40 → 28 → 20 · เจ้าของสั่งลดทีละ 30% มาห้ารอบ

   🔴 เจ้าของกำชับรอบนี้: **"ห้ามกระทบกล่องคุยจริง"**
      ปลอดภัยโดยโครงสร้าง ไม่ใช่โดยความระวัง — `heightFor()` แยกสองเส้นขาดกัน:
        · `!accepted` → คืนเลขนี้ตรง ๆ  (ห้องบอทดูแล / รอรับเคส / เคสปิด / เคสคนอื่น)
        · `accepted`  → คืน `remembered` หรือ `DEFAULT_COMPOSER_H` (120)
      ⇒ เลขนี้ **ไปไม่ถึง**ห้องที่คุยได้เลยแม้แต่ทางเดียว · `DEFAULT_COMPOSER_H`,
        `MIN_H` (39), `MAX_H` (416) ไม่ถูกแตะสักตัว การลากในห้องที่คุยจริงเท่าเดิมเป๊ะ

   ⚠️ ต่ำกว่า `MIN_H` (39) ได้ และตั้งใจให้ได้ — เลขนี้**ไม่ผ่าน clamp**
      `heightFor()` เข้า `setAreaH` ตรง ๆ (TicketChat.tsx:4542,4545) ส่วน
      `Math.max(MIN_H, …)` ใช้เฉพาะตอนลากด้วยมือ (:4557)
      เหตุผลที่แยกกันได้: ห้องที่ยังไม่รับเคสพิมพ์ไม่ได้อยู่แล้ว (มีปุ่ม
      "เปิดเคส"/"บอทกำลังดูแล" ทับอยู่) ⇒ ไม่ต้องเผื่อที่ให้ข้อความหนึ่งบรรทัด
      แต่ห้องที่คุยได้ยังต้องเผื่อ จึงยังคง MIN_H ไว้ที่ 39 ไม่แตะ
   revert: เปลี่ยนกลับเป็น 28 แล้วแก้ตัวเลขในเทส composerHeightMemory.test.ts */
export const IDLE_COMPOSER_H = 20;

/**
 * ความสูงที่ควรใช้ ณ ตอนนี้
 * @param accepted  ห้องนี้เป็นเคสของเราและกำลังคุยอยู่หรือไม่
 * @param remembered ค่าที่ผู้ใช้ลากไว้ล่าสุด (ใช้ร่วมกันทุกห้องที่คุย)
 */
export const heightFor = (accepted: boolean, remembered: number | null): number => {
  // ห้องที่พิมพ์ไม่ได้ ไม่สนใจค่าที่จำไว้เลย — เตี้ยคงที่เสมอ
  if (!accepted) return IDLE_COMPOSER_H;
  return remembered !== null ? remembered : DEFAULT_COMPOSER_H;
};

/**
 * ควรจำค่านี้ไว้ไหมหลังผู้ใช้ลากเสร็จ — จำเฉพาะตอนคุยจริงเท่านั้น
 * (ลากในห้องบอทดูแล/รอเปิดเคส = ใช้ได้ในจอนั้น แต่ไม่ติดไปห้องอื่น)
 */
export const shouldRemember = (accepted: boolean): boolean => accepted;
