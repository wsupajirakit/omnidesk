/** action ที่แปลว่า "แอดมินกดปุ่ม refresh เอง" — ชื่อเดิมของระบบ ไม่ได้ตั้งใหม่ */
export const PANEL_REFRESH_ACTION = 'manual_refresh';

/** action ที่แปลว่า "แอดมินเพิ่งคลิกการ์ดเข้าห้อง" — เจ้าของภาษาเดียวกับฝั่ง BE */
export const PANEL_OPEN_ACTION = 'chat_opened';

/**
 * event นี้ควรทำให้ทั้งแผงรีเฟรชไหม
 *
 * สองจังหวะที่แอดมิน "คาดหวังว่าจะเห็นของสด":
 *   `manual_refresh` — กดปุ่มเอง
 *   `chat_opened`    — เพิ่งคลิกการ์ดเข้าห้อง (raw profile กับ site rules
 *                      สดอยู่แล้วตั้งแต่ [FEAT-20260825-CHATOPENFRESH]
 *                      ⇒ การ์ดที่เหลือต้องสดพร้อมกัน ไม่งั้นครึ่งแผงสด ครึ่งแผงเก่า)
 *
 * ⚠️ **แก้เหตุผลที่เคยเขียนไว้ผิดในไฟล์นี้เอง (25/08):** เดิมกัน `chat_opened`
 *    ออกเพราะกลัว "โน๊ตที่แอดมินพิมพ์ค้างไว้จะหายตอน remount" — **ข้อกังวลนั้นผิด**
 *    `panelCardKey` มี id ของลูกค้าอยู่ด้วย ⇒ สลับห้องเมื่อไหร่ key ก็เปลี่ยนและ
 *    remount อยู่แล้ว draft จึงข้ามห้างไม่ได้ตั้งแต่แรก · เคสที่พังจริงคือ
 *    **คลิกกลับเข้าห้องเดิม** ซึ่ง id เท่าเดิม ⇒ ไม่ remount ⇒ เห็นของเก่า
 *    ซึ่งเป็นอาการที่ต้องแก้พอดี
 *
 * ⚠️ ยังกัน `case_taken` และ push จาก BE ไว้ — สองอันนั้นเกิดขึ้น "ระหว่าง" ที่
 *    แอดมินทำงานอยู่ในห้อง (กดรับเคส / ลูกค้าผูกบัญชี) การ remount ตอนนั้นคือ
 *    การกระชากแผงใต้มือคนที่กำลังพิมพ์อยู่จริง ๆ
 */
export const shouldRefreshPanel = (action: unknown): boolean =>
  action === PANEL_REFRESH_ACTION || action === PANEL_OPEN_ACTION;

/**
 * key ของการ์ดที่ต้อง remount
 *
 * ⚠️ มี `id` อยู่ด้วยเสมอ ไม่ใช่ nonce เดี่ยว ๆ — สลับไปดูลูกค้าคนอื่นต้อง remount
 *    เหมือนกัน ไม่งั้นการ์ดจะยังถือข้อมูลของคนก่อนหน้าค้างอยู่
 */
export const panelCardKey = (
  base: string,
  id: string | null | undefined,
  nonce: number,
): string => `${base}-${String(id ?? 'none')}-${nonce}`;
