/** จำกัดความยาวคีย์ — username จริงในระบบสั้นกว่านี้มาก */
export const LOGIN_USER_KEY_MAX_LEN = 64;

/**
 * @returns คีย์ที่ normalize แล้ว หรือ `''` เมื่อไม่มีชื่อผู้ใช้ที่ใช้ได้
 *          (`''` = ข้ามชั้นนี้ไปเลย ไม่นับ ไม่บล็อก — ปล่อยให้ชั้น IP กับ
 *          ValidationPipe จัดการ ซึ่งมันปฏิเสธ username ว่างอยู่แล้ว)
 */
export function normalizeLoginUsername(raw: unknown): string {
  if (typeof raw !== 'string') return '';

  // ขั้นนี้ต้องเหมือน auth.service.ts:69 ทุกตัวอักษร
  const sameAsLookup = raw.trim().toLowerCase();
  if (!sameAsLookup) return '';

  // ขั้นนี้เป็นเรื่องคีย์ Redis ล้วน ๆ: ยุบช่องว่าง/ขึ้นบรรทัดใหม่เป็น `_`
  // แล้วตัดความยาว. ชื่อที่ยาวเกิน 64 ตัวจะถูกตัดให้เท่ากัน — ยอมรับได้เพราะ
  // ระบบนี้ไม่มี username ยาวขนาดนั้น และผลที่แย่ที่สุดคือสองบัญชีนั้น
  // "แชร์โควตากัน" ซึ่งเข้มกว่าเดิม ไม่ใช่หลวมกว่าเดิม.
  return sameAsLookup.replace(/\s+/g, '_').slice(0, LOGIN_USER_KEY_MAX_LEN);
}
