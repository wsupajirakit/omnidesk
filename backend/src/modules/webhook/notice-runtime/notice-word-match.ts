/**
 * [FEAT-20260829-NOTICEWORDSPLAIN] คำละตินเทียบแบบ "ขอบคำ" ไม่ใช่ substring
 *
 * 🔴 เจ้าของสั่ง 29/08 ให้ใส่รูปธรรมดาอย่าง `cash` `credit` `in` `out` `pay`
 *    แต่ถ้าเทียบแบบ substring ล้วน คำสั้นพวกนี้จะไปตรง **กลางคำอื่น**:
 *      'in'  → th·in·g, po·in·t, m·in·e, w·in         ⇒ อังกฤษแทบทุกประโยคติด
 *      'out' → ab·out, y·out·h, r·out·e
 *      'pay' → (ปลอดภัยกว่า แต่ยังตรง 'paypal')
 *    ⇒ ใส่ตรง ๆ ไม่ได้ ไม่ใช่เพราะไม่อยากใส่ แต่เพราะการ์ดจะยิงมั่วทั้งระบบ
 *
 * ⇒ ทางออกคือเทียบละตินด้วย **ขอบคำ** (`\b`) ทำให้คำสั้นใช้ได้จริงตามที่สั่ง
 *    'in' ตรงกับ "money in" และ "in" เดี่ยว ๆ แต่ไม่ตรง "thing"
 *
 * ⚠️ ใช้กับคำที่เป็นอักษรละตินล้วนเท่านั้น — ไทย พม่า จีน ลาว เขมร **ไม่มีเว้นวรรค
 *    ระหว่างคำ** `\b` จึงใช้ไม่ได้และจะทำให้คำหายทั้งหมด ⇒ ภาษาเหล่านั้นยังเทียบ
 *    แบบ substring เหมือนเดิมทุกประการ (ไทยจึงไม่ขยับแม้แต่ช่องเดียว)
 * ⚠️ regex ถูกสร้างครั้งเดียวตอนโหลดโมดูล ไม่ได้สร้างใหม่ทุกข้อความ
 *
 * revert: ลบ `LATIN_RE`/`latinRe` แล้วให้ `matchAny` กลับไปใช้ `hay.includes(w)`
 *         อย่างเดียว และถอดคำละตินสั้น (`in`/`out`/`pay`/`cash`/`credit`) ออก
 */
const LATIN_ONLY = /^[a-z0-9][a-z0-9 ]*$/;
const ESCAPE_RE = /[.*+?^${}()|[\]\\]/g;
const latinRe = new Map<string, RegExp>();

function matchesWord(hay: string, w: string): boolean {
  if (!LATIN_ONLY.test(w)) return hay.includes(w);
  let re = latinRe.get(w);
  if (!re) {
    re = new RegExp(`\\b${w.replace(ESCAPE_RE, '\\$&')}\\b`);
    latinRe.set(w, re);
  }
  return re.test(hay);
}

function matchAny(text: unknown, words: readonly string[]): boolean {
  if (typeof text !== 'string' || text.length === 0) return false;
  const hay = text.toLowerCase();
  return words.some((w) => matchesWord(hay, w));
}

/** true = the text mentions deposits (per DEPOSIT_WORDS, substring match). */
export function matchDepositWord(text: unknown): boolean {
  return matchAny(text, DEPOSIT_WORDS);
}

/** true = the text mentions withdrawals (per WITHDRAW_WORDS, substring match). */
export function matchWithdrawWord(text: unknown): boolean {
  return matchAny(text, WITHDRAW_WORDS);
}
