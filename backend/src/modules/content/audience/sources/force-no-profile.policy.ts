/** สวิตช์เดียวจบ — `false` = ไม่บังคับอะไรเลย พฤติกรรมกลับไปเหมือนก่อน 25/08 */
export const FORCE_NO_PROFILE_ENABLED = true;

/**
 * คีย์ของ audience source ที่ทำให้ต้องบังคับ
 *
 * ⚠️ เป็น **คีย์ของ source** (ตามที่เก็บใน `audience.rules[].key`) ไม่ใช่ dotted
 *    path ของ member — ตัวกรองรู้จักงานผ่านคีย์ ไม่ได้รู้จักผ่าน path
 * ⚠️ ทั้งสามตัวเป็น RECORD ในถุง follow_up ที่ไม่มีใครลบ · ถ้าวันหนึ่งมีตัวไหน
 *    กลายเป็น FLAG ที่ถูกเคลียร์ตอนสมัครจริง ๆ ให้เอาออกจากลิสต์นี้ได้ เพราะ
 *    การบังคับจะกลายเป็นของซ้ำซ้อน (ไม่ผิด แต่ไม่จำเป็น)
 */
export const FORCE_NO_PROFILE_KEYS: readonly string[] = [
  'follow_up.customer_helper_at',
  'follow_up.request_reg_at',
  'follow_up.abandon_at',
];

/**
 * นิยามของ "ยังไม่ผูกข้อมูล"
 *
 * ⭐ `{raw_profile_data: null}` จับได้ทั้ง **ไม่มี field** และ **เป็น null จริง**
 *    ซึ่งครบทั้งสองสภาพที่แปลว่ายังไม่ผูก · ตรวจกับฐานจริง 25/08/2026:
 *    ไม่มี field = 0 · null = 25 · มีค่าจริง = 3 · **object ว่าง `{}` = 0 แถว**
 *    ⇒ ไม่ต้องเผื่อเคส `{}` ในคิวรี่ (ฝั่ง FE เผื่อไว้เพราะที่นั่นถูกกว่ามาก)
 * ⭐ **ไม่ใช้ `$exists`** ตามข้อห้ามของระบบ audience (ดู `audience-filter.ts`)
 * 🔴 **นี่คือจุดที่เงื่อนไข "ไม่เคยถูกล้างโปรไฟล์" จะมาลง** ถ้าวันหนึ่งตัดสินใจปิดรู
 *    ตามหัวข้อ [DOC-20260825-REGSTATUS] ที่หัวไฟล์ — เติม `raw_profile_cleared_at:
 *    null` เข้าไปใน object นี้ **ที่เดียวจบ** ไม่ต้องแตะไฟล์อื่นเลย
 *    ⚠️ วันนี้ยังไม่เติม และการที่มันไม่อยู่ตรงนี้ **ไม่ใช่การลืม** — อ่านข้อ
 *       "ราคาที่ควรถกก่อนทำ" ที่หัวไฟล์ก่อนเติม
 * ⚠️ ตัวมันเองเป็น COLLSCAN (วัดแล้ว docsExamined = ทั้งคอลเลกชัน) แต่มันถูก AND
 *    เข้ากับกฎ follow_up ที่มี index อยู่แล้วเสมอ ⇒ planner เดินจาก index ตัวนั้น
 *    แล้วค่อยกรองอันนี้ทีหลัง · ไม่ได้เพิ่มการสแกนใหม่
 */
export const NO_PROFILE_CLAUSE: Readonly<Record<string, unknown>> = {
  raw_profile_data: null,
};

/**
 * ต้องบังคับไหม เมื่อรู้ว่างานนี้ใช้ source คีย์อะไรบ้าง
 *
 * @returns clause ที่ต้อง AND เข้าไป หรือ `null` เมื่อไม่ต้องบังคับ
 */
export function forceNoProfileClause(
  usedKeys: readonly string[],
): Record<string, unknown> | null {
  if (!FORCE_NO_PROFILE_ENABLED) return null;
  const hit = usedKeys.some((k) => FORCE_NO_PROFILE_KEYS.includes(k));
  return hit ? { ...NO_PROFILE_CLAUSE } : null;
}
