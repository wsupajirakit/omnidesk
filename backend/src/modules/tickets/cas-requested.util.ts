/** คีย์เดียวที่ฟังก์ชันนี้สนใจ — ประกาศไว้ที่เดียวกับกติกา ไม่ให้พิมพ์ซ้ำที่อื่น */
export const CAS_EXPECTED_OWNER_FIELD = 'expected_admin_user_id';

/**
 * true = ผู้เรียก **ส่ง** เงื่อนไขเจ้าของมาจริง ⇒ ต้องเอาไปใส่ฟิลเตอร์ของคำสั่งเขียน
 *
 * @param body ตัว `updateData` ที่ service ถืออยู่ (คัดลอกมาจาก DTO แล้ว)
 */
export function isCasRequested(body: Record<string, unknown>): boolean {
  return body?.[CAS_EXPECTED_OWNER_FIELD] !== undefined;
}

/**
 * อ่าน "เจ้าของ" ออกมาเป็นข้อความเพื่อเปรียบเทียบ — รับได้ทั้ง `ObjectId` และ string
 *
 * ⚠️ ห้ามใช้ `String(v)` ตรง ๆ กับค่า `unknown` — ถ้ามันเป็น object ที่ไม่มี `toString`
 * ของตัวเอง จะได้ `"[object Object]"` แล้วการเปรียบเทียบจะ **ไม่มีวันเท่ากัน**
 * เงียบ ๆ (eslint `no-base-to-string` จับให้ตอนเขียน fix นี้พอดี) — และนั่นคือ
 * กับดักตระกูลเดียวกับบั๊กที่ไฟล์นี้เกิดมาเพื่อแก้ ⇒ อะไรที่ไม่ใช่ id = สตริงว่าง
 *
 * `''` แปลว่า "ไม่มีเจ้าของ / อ่านไม่ได้" ซึ่งเทียบกันได้อย่างปลอดภัยทั้งสองฝั่ง
 */
export function casOwnerText(value: unknown): string {
  if (typeof value === 'string') return value;
  const oid = value as { toHexString?: () => string } | null | undefined;
  return typeof oid?.toHexString === 'function' ? oid.toHexString() : '';
}
